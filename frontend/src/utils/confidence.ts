export type ConfidenceLevel = 'high' | 'medium' | 'low'

export interface ConfidenceThresholds {
  autoApproveThreshold: number
  humanReviewThreshold: number
}

/**
 * Display band of an AI confidence value, using the backend's configured governance thresholds. This is
 * presentation only: routing decisions are made by the backend's approval policy.
 */
export function confidenceLevel(confidence: number, thresholds: ConfidenceThresholds | undefined): ConfidenceLevel | null {
  if (!thresholds) {
    return null
  }
  if (confidence >= thresholds.autoApproveThreshold) {
    return 'high'
  }
  return confidence >= thresholds.humanReviewThreshold ? 'medium' : 'low'
}

export const CONFIDENCE_DISCLAIMER =
  'Confidence is generated by the AI workflow and should not be interpreted as guaranteed accuracy.'
