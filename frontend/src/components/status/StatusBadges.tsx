export type Tone = 'neutral' | 'muted' | 'success' | 'warning' | 'danger' | 'info' | 'ai'

const TONES: Record<Tone, string> = {
  neutral: 'border-border bg-muted/60 text-foreground',
  muted: 'border-border bg-transparent text-muted-foreground',
  success: 'border-emerald-200 bg-emerald-50 text-emerald-800 dark:border-emerald-900 dark:bg-emerald-950 dark:text-emerald-300',
  warning: 'border-amber-200 bg-amber-50 text-amber-900 dark:border-amber-900 dark:bg-amber-950 dark:text-amber-300',
  danger: 'border-red-200 bg-red-50 text-red-800 dark:border-red-900 dark:bg-red-950 dark:text-red-300',
  info: 'border-sky-200 bg-sky-50 text-sky-800 dark:border-sky-900 dark:bg-sky-950 dark:text-sky-300',
  ai: 'border-violet-200 bg-violet-50 text-violet-800 dark:border-violet-900 dark:bg-violet-950 dark:text-violet-300',
}

interface PillProps {
  tone?: Tone
  icon?: ComponentType<{ className?: string }>
  children: ReactNode
  className?: string
  title?: string
  spin?: boolean
}

/** Compact status label: tone + icon + text, so meaning never depends on colour alone. */
export function Pill({ tone = 'neutral', icon: Icon, children, className, title, spin }: PillProps) {
  return (
    <span
      title={title}
      className={cn(
        'inline-flex h-5 shrink-0 items-center gap-1 rounded-md border px-1.5 text-[11px] leading-none font-medium whitespace-nowrap',
        TONES[tone],
        className,
      )}
    >
      {Icon && <Icon aria-hidden className={cn('size-3 shrink-0', spin && 'animate-spin')} />}
      {children}
    </span>
  )
}

