/**
 * Renders the backend's review policy for a proposal: whether the schema requires a human decision, allows
 * automatic application, or neither. The UI never derives this itself.
 */
export function PolicyBadge({ policy }: { policy: ReviewPolicy }) {
  if (policy.requiresHumanApproval) {
    return (
      <Pill tone="danger" icon={UserCheck} title="The metadata schema requires a human decision for AI values of this field">
        Human approval required
      </Pill>
    )
  }
  if (policy.canAutoApprove) {
    return (
      <Pill tone="success" icon={ShieldCheck} title="The schema allows AI values of this field to be applied automatically above the confidence threshold">
        Auto-approvable field
      </Pill>
    )
  }
  return (
    <Pill tone="info" icon={UserCheck} title="The schema does not allow automatic application; a reviewer decides">
      Manual review field
    </Pill>
  )
}

